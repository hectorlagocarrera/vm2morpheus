"""Builds the application icons from the Redes globe (assets/globe-source.png).

Run:  python tools/make_icons.py        (needs Pillow, a dev-only dependency)

The source is a small opaque picture on a white background, so the white is turned into transparency first
(keeping the brand orange), then the globe is placed on a white rounded tile with a margin and scaled to each size.
Outputs: assets/vm2morpheus.ico (exe + Explorer + taskbar), assets/favicon.ico, assets/icon-192.png and
vm2morpheus/icon_data.py (the browser icons, embedded so the single folder build needs no extra files)."""
import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
EXE_SIZES = [16, 24, 32, 48, 64, 128, 256]
FAVICON_SIZES = [16, 32, 48]
MARGIN = 0.14  # empty border between the tile edge and the globe, as a fraction of the icon size


def white_to_alpha(img: Image.Image) -> Image.Image:
    """Opaque art on white -> the same art on transparency, keeping its orange-to-red gradient.

    For a pixel p over white, p = c*a + 255*(1-a). Taking a = 255 - min(r,g,b) as the coverage and solving for the
    colour c gives the original saturated colours without a white halo."""
    img = img.convert("RGB")
    out = Image.new("RGBA", img.size)
    pixels = []
    for r, g, b in img.getdata():
        a = 255 - min(r, g, b)
        if a == 0:
            pixels.append((0, 0, 0, 0))
            continue
        k = 255 / a
        pixels.append((min(255, round((r - 255 + a) * k)), min(255, round((g - 255 + a) * k)),
                       min(255, round((b - 255 + a) * k)), a))
    out.putdata(pixels)
    return out


def tile(size: int) -> Image.Image:
    """White rounded square with a faint border, drawn 4x larger and shrunk so the corners are smooth."""
    big = size * 4
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    ImageDraw.Draw(img).rounded_rectangle([0, 0, big - 1, big - 1], radius=round(big * 0.22),
                                          fill=(255, 255, 255, 255), outline=(208, 213, 221, 255),
                                          width=max(4, big // 40))
    return img.resize((size, size), Image.LANCZOS)


def square_canvas(globe: Image.Image, size: int) -> Image.Image:
    """The globe centred on a white tile, so it stays legible on light and dark taskbars and browser tabs."""
    side = max(globe.size)
    square = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    square.paste(globe, ((side - globe.width) // 2, (side - globe.height) // 2), globe)
    inner = round(size * (1 - 2 * MARGIN))
    mark = square.resize((inner, inner), Image.LANCZOS)
    if size <= 48:  # thin lines vanish when shrunk: strengthen the coverage so the globe stays readable
        gamma = 0.45 if size <= 24 else 0.6
        r, g, b, a = mark.split()
        mark = Image.merge("RGBA", (r, g, b, a.point(lambda v: min(255, round(255 * (v / 255) ** gamma)))))
    out = tile(size)
    out.alpha_composite(mark, ((size - inner) // 2, (size - inner) // 2))
    return out


def ico_bytes(globe: Image.Image, sizes: list[int]) -> bytes:
    frames = [square_canvas(globe, s) for s in sizes]
    buf = io.BytesIO()
    frames[-1].save(buf, format="ICO", sizes=[(s, s) for s in sizes], append_images=frames[:-1])
    return buf.getvalue()


def main() -> None:
    globe = white_to_alpha(Image.open(ROOT / "assets" / "globe-source.png"))
    exe_ico = ico_bytes(globe, EXE_SIZES)
    fav_ico = ico_bytes(globe, FAVICON_SIZES)
    png = io.BytesIO()
    square_canvas(globe, 192).save(png, format="PNG", optimize=True)
    (ROOT / "assets" / "vm2morpheus.ico").write_bytes(exe_ico)
    (ROOT / "assets" / "favicon.ico").write_bytes(fav_ico)
    (ROOT / "assets" / "icon-192.png").write_bytes(png.getvalue())
    b64 = lambda data: "\n".join(f'    "{base64.b64encode(data).decode()[i:i + 100]}"'  # noqa: E731
                                 for i in range(0, len(base64.b64encode(data)), 100))
    (ROOT / "vm2morpheus" / "icon_data.py").write_text(
        '"""Browser icons (generated by tools/make_icons.py; do not edit by hand)."""\nimport base64\n\n'
        f"FAVICON_ICO = base64.b64decode(\n{b64(fav_ico)}\n)\n"
        f"ICON_PNG = base64.b64decode(\n{b64(png.getvalue())}\n)\n", encoding="utf-8")
    print(f"vm2morpheus.ico {len(exe_ico)} B, favicon.ico {len(fav_ico)} B, icon-192.png {len(png.getvalue())} B")


if __name__ == "__main__":
    main()
